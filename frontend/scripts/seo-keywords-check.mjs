/**
 * Vérifie que les mots-clés de scripts/seo-keywords.json sont présents dans le HTML généré (dist/)
 * et met à jour la table d’implémentation de docs/seo-keyword-map.md (entre les marqueurs).
 * Usage : node scripts/seo-keywords-check.mjs   (après `npm run build`). Code de sortie 1 si un mot-clé
 * principal manque dans le titre, le H1 ou le corps de la page.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const { pages } = JSON.parse(readFileSync('scripts/seo-keywords.json', 'utf8'))

const norm = (s) =>
  s
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#x27;|&#39;|’/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&/g, ' and ')
    .toLowerCase()
    .replace(/[^a-z0-9àâçéèêëîïôûùüÿñ' ]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
const has = (hay, needle) => hay.includes(norm(needle))
const count = (hay, needle) => hay.split(norm(needle)).length - 1

const rows = []
let failures = 0
for (const page of pages) {
  const html = readFileSync(join('dist', page.path, 'index.html'), 'utf8')
  const title = norm((html.match(/<title>([^<]*)/) || ['', ''])[1])
  const description = norm((html.match(/name="description" content="([^"]*)"/) || ['', ''])[1])
  const h1 = norm((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || ['', ''])[1])
  const h2s = [...html.matchAll(/<h2[^>]*>([\s\S]*?)<\/h2>/g)].map((m) => norm(m[1]))
  const alts = [...html.matchAll(/ alt="([^"]*)"/g)].map((m) => norm(m[1]))
  const anchors = [...html.matchAll(/<a [^>]*>([\s\S]*?)<\/a>/g)].map((m) => norm(m[1]))
  const main = (html.match(/<main[^>]*>([\s\S]*?)<\/main>/) || ['', html])[1]
  const body = norm(main.replace(/<script[\s\S]*?<\/script>/g, ' '))

  const inTitle = has(title, page.primary)
  const inDesc = has(description, page.primary)
  const inH1 = has(h1, page.primary)
  const bodyCount = count(body, page.primary)
  const sec = page.secondary.map((k) => ({
    k,
    body: count(body, k),
    h2: h2s.some((h) => has(h, k)),
    alt: alts.some((a) => has(a, k)),
    anchor: anchors.some((a) => has(a, k)),
  }))
  const secPresent = sec.filter((s) => s.body > 0).length
  const ok = inTitle && inH1 && bodyCount >= 1 && secPresent >= Math.min(3, page.secondary.length)
  if (!ok) failures += 1

  const secCell = sec
    .map((s) => `${s.k} (${s.body}${s.h2 ? ', H2' : ''}${s.alt ? ', alt' : ''}${s.anchor ? ', link' : ''})`)
    .join('; ')
  rows.push(
    `| \`${page.path}\` | ${page.primary} | title ${inTitle ? '✓' : '✗'} · meta ${inDesc ? '✓' : '✗'} · H1 ${inH1 ? '✓' : '✗'} · body ×${bodyCount} | ${secCell} | ${ok ? 'Implemented (volumes unvalidated)' : '**Missing**'} |`,
  )
  console.log(`${page.path.padEnd(36)} primary: title=${inTitle ? 'Y' : 'N'} meta=${inDesc ? 'Y' : 'N'} h1=${inH1 ? 'Y' : 'N'} body=${bodyCount} | secondary in body: ${secPresent}/${page.secondary.length}${ok ? '' : '   <-- MISSING'}`)
}

const table = [
  '| Page | Primary keyword | Primary: where found | Secondary keywords (body occurrences; H2 / alt / link when present) | Status |',
  '|---|---|---|---|---|',
  ...rows,
].join('\n')

const mapPath = '../docs/seo-keyword-map.md'
const md = readFileSync(mapPath, 'utf8')
const start = '<!-- keyword-table:start -->'
const end = '<!-- keyword-table:end -->'
if (md.includes(start) && md.includes(end)) {
  const updated = md.slice(0, md.indexOf(start) + start.length) + `\n_Generated by \`node scripts/seo-keywords-check.mjs\` on ${new Date().toISOString().slice(0, 10)} from the built HTML in \`dist/\`._\n\n${table}\n` + md.slice(md.indexOf(end))
  writeFileSync(mapPath, updated, 'utf8')
  console.log(`\nTable written to ${mapPath}`)
} else {
  console.log('\n' + table)
}
console.log(failures ? `\n${failures} page(s) missing their primary keyword` : '\nAll primary keywords present in title, H1 and body')
process.exitCode = failures ? 1 : 0
